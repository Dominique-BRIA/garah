-- Correction A4 : le modèle initial rendait le retour PARTIEL impossible.
-- Un retour porte désormais sur des LIGNES, avec des quantités et un état
-- d'article — parce que « il renvoie 3 chemises sur 10, dont 1 abîmée » est
